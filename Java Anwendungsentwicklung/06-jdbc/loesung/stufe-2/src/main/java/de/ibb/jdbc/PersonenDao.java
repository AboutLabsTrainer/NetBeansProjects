package de.ibb.jdbc;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import javax.sql.DataSource;

public class PersonenDao {

    private final DataSource dataSource;

    public PersonenDao(DataSource dataSource) {
        this.dataSource = dataSource;
    }

    public void erstelleTabelle() {
        String sql = """
            CREATE TABLE IF NOT EXISTS jae06_personen (
                id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(100) NOT NULL,
                lebensalter INT,
                email VARCHAR(100)
            )
            """;
        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute(sql);
        } catch (SQLException ex) {
            throw new IllegalStateException(ex);
        }
    }

    public int speichere(String name, int lebensalter, String email) {
        String sql = "INSERT INTO jae06_personen (name, lebensalter, email) VALUES (?, ?, ?)";
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, name);
            ps.setInt(2, lebensalter);
            ps.setString(3, email);
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) {
                    return keys.getInt(1);
                }
            }
        } catch (SQLException ex) {
            throw new IllegalStateException(ex);
        }
        throw new IllegalStateException("Keine generierte ID");
    }

    public String findeName(int id) {
        String sql = "SELECT name FROM jae06_personen WHERE id = ?";
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    return rs.getString("name");
                }
            }
        } catch (SQLException ex) {
            throw new IllegalStateException(ex);
        }
        return null;
    }
}
