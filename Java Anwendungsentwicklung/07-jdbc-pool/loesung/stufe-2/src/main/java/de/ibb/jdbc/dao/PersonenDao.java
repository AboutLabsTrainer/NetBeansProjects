package de.ibb.jdbc.dao;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import javax.sql.DataSource;

public class PersonenDao {

    private final DataSource dataSource;

    public PersonenDao(DataSource dataSource) {
        this.dataSource = dataSource;
    }

    public void erstelleTabelle() {
        String sql = """
            CREATE TABLE IF NOT EXISTS personen (
                id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(100) NOT NULL,
                lebensalter INT,
                email VARCHAR(100)
            )
            """;
        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute(sql);
        } catch (SQLException ex) {
            throw new IllegalStateException(ex);
        }
    }

    public Person save(Person person) {
        String sql = "INSERT INTO personen (name, lebensalter, email) VALUES (?, ?, ?)";
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, person.name());
            ps.setInt(2, person.alter());
            ps.setString(3, person.email());
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) {
                    return person.withId(keys.getInt(1));
                }
            }
        } catch (SQLException ex) {
            throw new IllegalStateException(ex);
        }
        throw new IllegalStateException("Keine generierte ID");
    }

    public long count() {
        String sql = "SELECT COUNT(*) FROM personen";
        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {
            if (rs.next()) {
                return rs.getLong(1);
            }
            return 0;
        } catch (SQLException ex) {
            throw new IllegalStateException(ex);
        }
    }
}
